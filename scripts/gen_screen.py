#!/usr/bin/env python3
"""Generates src/fpga/core/status_screen.v (Pocket-style UI).

Strings live here so their lengths and centring are computed, not hand-counted.
Every text line is a 40-character (320-bit) vector, column 0 in the MSBs.
"""
import sys

A, B, DOT, CHK, X, UD = "\x01", "\x02", "\x03", "\x04", "\x05", "\x06"

def lit(s):
    """Verilog literal for s (handles the glyph control chars)."""
    parts, buf = [], ""
    for ch in s:
        if ord(ch) < 32:
            if buf: parts.append('"%s"' % buf); buf = ""
            parts.append("8'h%02x" % ord(ch))
        else:
            buf += ch
    if buf: parts.append('"%s"' % buf)
    return "{" + ", ".join(parts) + "}" if len(parts) > 1 else parts[0]

def left(s, col=0):
    assert col + len(s) <= 40, s
    if not s:
        return "{40{8'h00}}"
    p = []
    if col: p.append("{%d{8'h00}}" % col)
    p.append(lit(s))
    r = 40 - col - len(s)
    if r: p.append("{%d{8'h00}}" % r)
    return "{" + ", ".join(p) + "}"

def center(s):
    return left(s, (40 - len(s)) // 2)

def case_table(name, sel, width, items, default="", how=center):
    out = ["always @(*) begin", "    case (%s)" % sel]
    for k, v in items:
        out.append("    %d'd%d: %s = %s;" % (width, k, name, how(v)))
    out.append("    default: %s = %s;" % (name, how(default)))
    out += ["    endcase", "end"]
    return "\n".join(out)

STATUS = {   # code: (headline, detail1, detail2)
    0:  ("Waiting for cartridge", "", ""),
    1:  ("Reading cartridge", "", ""),
    2:  ("No cartridge found", "Insert a GB, GBC or GBA cartridge", "with the Pocket powered off."),
    3:  ("Reading cartridge", "", ""),
    4:  ("No save on this cartridge", "", ""),
    5:  ("Reading save", "", ""),
    6:  ("EEPROM did not answer", "The save looks blank or the chip", "is not responding."),
    7:  ("Writing to SD card", "", ""),
    8:  ("Done", "", ""),
    9:  ("SD card error", "The file could not be written.", ""),
    10: ("Too many backups", "Up to 99 backups per game.", "Move some off the SD card."),
    11: ("SD card not responding", "", ""),
    12: ("Safety stop", "A cartridge write was blocked.", "Nothing was written. Restart."),
    13: ("Ready to read", "This cartridge needs read commands", "on its bus. Its save is not changed."),
    14: ("Unstable read", "Two reads did not match.", "Clean the contacts and retry."),
    15: ("Cartridge changed", "The cartridge was removed or", "swapped while reading."),
    16: ("Cancelled", "", ""),
    17: ("Verifying", "", ""),
    18: ("Cartridge power lost", "Power the Pocket off and on.", ""),
    19: ("Reading ROM", "", ""),
    20: ("Unsupported cartridge", "This mapper is not supported yet.", ""),
    21: ("", "", ""),
    22: ("Reading cartridge", "", ""),
}
SAVE = {0: "None", 1: "SRAM 32 KB", 2: "Flash 64 KB", 3: "Flash 128 KB",
        4: "EEPROM 512 B", 5: "EEPROM 8 KB", 6: "EEPROM", 7: "SRAM 2 KB",
        8: "SRAM 8 KB", 9: "SRAM 32 KB", 10: "SRAM 64 KB", 11: "SRAM 128 KB",
        12: "MBC2 512 B"}
ROM = {15: "32 KB", 16: "64 KB", 17: "128 KB", 18: "256 KB", 19: "512 KB",
       20: "1 MB", 21: "2 MB", 22: "4 MB", 23: "8 MB", 24: "16 MB", 25: "32 MB"}
MAPPER = {0: "ROM only", 1: "MBC1", 2: "MBC2", 3: "MBC3", 5: "MBC5", 7: "Unknown"}
MENU = ["Back up save", "Back up ROM", "Back up save + ROM", "Rescan cartridge"]
DONE = {1: "Save backed up", 2: "ROM backed up", 3: "Save and ROM backed up"}

def right_value(table, sel, width, name, endcol=34):
    out = ["always @(*) begin", "    case (%s)" % sel]
    for k, v in table.items():
        out.append("    %d'd%d: %s = %s;" % (width, k, name, left(v, endcol - len(v))))
    out.append("    default: %s = {40{8'h00}};" % name)
    out += ["    endcase", "end"]
    return "\n".join(out)

head = case_table("t_head", "status", 5, [(k, v[0]) for k, v in STATUS.items()])
det1 = case_table("t_det1", "status", 5, [(k, v[1]) for k, v in STATUS.items()])
det2 = case_table("t_det2", "status", 5, [(k, v[2]) for k, v in STATUS.items()])
done = case_table("t_done", "done_what", 2, list(DONE.items()), "Done")
savev = right_value(SAVE, "save_label", 4, "t_savev")
romv = right_value(ROM, "rom_log2", 5, "t_romv")
mapv = right_value(MAPPER, "mapper", 3, "t_mapv")
menu = case_table("t_item", "item_idx", 2, list(enumerate(MENU)), how=lambda s: left(s, 8))

hints = {
    "menu":    center(UD + " Choose     " + A + " Select"),
    "result":  center(A + " Back to menu"),
    "nocart":  center(A + " Try again"),
    "confirm": center(A + " Continue     " + B + " Back"),
    "fatal":   center("Restart the core from the menu"),
    "busy":    center("Do not remove the cartridge"),
}

V = r'''//
// status_screen.v - SaveSiphon UI, 320x240, Pocket-style  (GENERATED by
// scripts/gen_screen.py - edit the generator, not this file)
//
// Black background, white text, grey secondary text, a white highlight bar
// for the selected menu row and a thin progress bar. 8x8 font, title at 2x.
// Inputs come from the clk_74a domain and change slowly; the clocks are
// declared asynchronous, so a torn frame is the worst case.
//

`default_nettype none

module status_screen (
    input  wire         clk,            // ~12.288 MHz pixel clock

    input  wire [2:0]   ui_mode,        // 0 busy, 1 menu, 2 result, 3 confirm
    input  wire [1:0]   menu_sel,
    input  wire [4:0]   status,
    input  wire [7:0]   progress,
    input  wire [2:0]   err_code,
    input  wire [2:0]   fault_code,
    input  wire [1:0]   cart_kind,
    input  wire [127:0] name_flat,
    input  wire [4:0]   name_len,
    input  wire [31:0]  code_flat,
    input  wire         code_len,
    input  wire [3:0]   save_label,
    input  wire [4:0]   rom_log2,
    input  wire [2:0]   mapper,
    input  wire [1:0]   done_what,
    input  wire [511:0] path_flat,

    output reg  [23:0]  rgb,
    output reg          de,
    output reg          hs,
    output reg          vs
);

localparam [9:0] H_BP = 10'd10, H_ACT = 10'd320, H_TOT = 10'd400;
localparam [9:0] V_BP = 10'd10, V_ACT = 10'd240, V_TOT = 10'd512;

localparam [23:0] C_BG    = 24'h000000;
localparam [23:0] C_FG    = 24'hF2F2F2;
localparam [23:0] C_DIM   = 24'h8C8C8C;
localparam [23:0] C_FAINT = 24'h3A3A3A;
localparam [23:0] C_BAR   = 24'hF2F2F2;     // highlight bar (text drawn black)
localparam [23:0] C_OK    = 24'h5BD27A;
localparam [23:0] C_BAD   = 24'hFF6159;

localparam [2:0] UI_BUSY = 3'd0, UI_MENU = 3'd1, UI_RESULT = 3'd2, UI_CONFIRM = 3'd3;

// text rows (top y of the 8 px glyph)
localparam [9:0] Y_TITLE = 10'd18;    // 2x, 16 px tall
localparam [9:0] Y_NAME  = 10'd50;
localparam [9:0] Y_SUB   = 10'd62;
localparam [9:0] Y_RULE  = 10'd78;
localparam [9:0] Y_R0    = 10'd92;
localparam [9:0] Y_R1    = 10'd112;
localparam [9:0] Y_R2    = 10'd132;
localparam [9:0] Y_R3    = 10'd152;
localparam [9:0] Y_I0    = 10'd176;
localparam [9:0] Y_I1    = 10'd188;
localparam [9:0] Y_HINT  = 10'd220;
localparam [9:0] Y_PBAR  = 10'd130;   // progress bar, 3 px tall

// ------------------------------------------------------------ font
reg [7:0] font [0:1023];
initial $readmemh("core/font.hex", font);

// ------------------------------------------------------------ timing
reg [9:0] x = 10'd0, y = 10'd0;
always @(posedge clk) begin
    if (x == H_TOT - 10'd1) begin
        x <= 10'd0;
        y <= (y == V_TOT - 10'd1) ? 10'd0 : y + 10'd1;
    end else begin
        x <= x + 10'd1;
    end
end
wire       active = (x >= H_BP) && (x < H_BP + H_ACT) && (y >= V_BP) && (y < V_BP + V_ACT);
wire [9:0] vx = x - H_BP;
wire [9:0] vy = y - V_BP;

// ------------------------------------------------------------ strings
reg [319:0] t_head, t_det1, t_det2, t_done, t_savev, t_romv, t_mapv, t_item;
reg [1:0]   item_idx;

@HEAD@

@DET1@

@DET2@

@DONE@

@SAVEV@

@ROMV@

@MAPV@

@MENU@

function [7:0] printable;
    input [7:0] c;
    printable = (c >= 8'h20 && c < 8'h7F) ? c : 8'h00;
endfunction

// cart name, centred; GBA adds " . CODE" to the subtitle
reg [319:0] t_name, t_sub, t_file, t_err;
reg [5:0]   nshift, flen;
integer i;
always @(*) begin
    t_name = {40{8'h00}};
    for (i = 0; i < 16; i = i + 1)
        if (i < name_len) t_name[319-8*i -: 8] = printable(name_flat[127-8*i -: 8]);
    nshift = (6'd40 - {1'b0, name_len}) >> 1;
    t_name = t_name >> {nshift, 3'b000};

    case (cart_kind)
    2'd1: t_sub = {@GBA_SUB@, code_flat[31:24], code_flat[23:16], code_flat[15:8], code_flat[7:0], {@GBA_SUB_PAD@{8'h00}}};
    2'd2: t_sub = @GB_SUB@;
    2'd3: t_sub = @GBC_SUB@;
    default: t_sub = {40{8'h00}};
    endcase

    // file name after "/Assets/savesiphon/common/" (26 bytes), centred
    t_file = {40{8'h00}};
    flen   = 6'd0;
    for (i = 0; i < 36; i = i + 1) begin
        t_file[319-8*i -: 8] = printable(path_flat[511-8*(26+i) -: 8]);
        if (path_flat[511-8*(26+i) -: 8] != 8'h00) flen = i + 1;
    end
    t_file = t_file >> {((6'd40 - flen) >> 1), 3'b000};

    if (status == 5'd12) begin
        t_err = @GRD_LINE@;
        t_err[319-8*@GRD_COL@ -: 8] = "0" + {5'd0, fault_code};
    end else begin
        t_err = @ERR_LINE@;
        t_err[319-8*@ERR_COL@ -: 8] = "0" + {5'd0, err_code};
    end
end

wire st_bad  = (status == 5'd2) || (status == 5'd4) || (status == 5'd6) ||
               (status >= 5'd9 && status <= 5'd12) || (status == 5'd14) ||
               (status == 5'd15) || (status == 5'd18) || (status == 5'd20);
wire fatal   = (status == 5'd12) || (status == 5'd18);
wire is_gb   = cart_kind[1];
wire no_save = (save_label == 4'd0);

// ------------------------------------------------------------ stage A: where are we
reg [3:0]  slot_a;      // which text line, 0 = none
reg [5:0]  col_a;
reg [2:0]  fy_a, fx_a;
reg        act_a, title_a, bar_a, pbar_a, pfill_a, rule_a;
reg [1:0]  row_a;
wire       in_title = (vy >= Y_TITLE) && (vy < Y_TITLE + 10'd16) && (vx >= 10'd80) && (vx < 10'd240);
wire [9:0] tx = vx - 10'd80;
wire [9:0] ty = vy - Y_TITLE;

function in_row;
    input [9:0] yy, top;
    in_row = (yy >= top) && (yy < top + 10'd8);
endfunction

always @(posedge clk) begin
    act_a   <= active;
    title_a <= in_title;
    col_a   <= in_title ? {2'b00, tx[7:4]} : vx[8:3];
    fx_a    <= in_title ? tx[3:1] : vx[2:0];
    slot_a  <= 4'd0;
    fy_a    <= vy[2:0];
    row_a   <= 2'd0;
    if (in_title)              begin slot_a <= 4'd15; fy_a <= ty[3:1]; end
    else if (in_row(vy, Y_NAME)) begin slot_a <= 4'd1; fy_a <= vy - Y_NAME; end
    else if (in_row(vy, Y_SUB))  begin slot_a <= 4'd2; fy_a <= vy - Y_SUB;  end
    else if (in_row(vy, Y_R0))   begin slot_a <= 4'd3; fy_a <= vy - Y_R0; row_a <= 2'd0; end
    else if (in_row(vy, Y_R1))   begin slot_a <= 4'd4; fy_a <= vy - Y_R1; row_a <= 2'd1; end
    else if (in_row(vy, Y_R2))   begin slot_a <= 4'd5; fy_a <= vy - Y_R2; row_a <= 2'd2; end
    else if (in_row(vy, Y_R3))   begin slot_a <= 4'd6; fy_a <= vy - Y_R3; row_a <= 2'd3; end
    else if (in_row(vy, Y_I0))   begin slot_a <= 4'd7; fy_a <= vy - Y_I0; end
    else if (in_row(vy, Y_I1))   begin slot_a <= 4'd8; fy_a <= vy - Y_I1; end
    else if (in_row(vy, Y_HINT)) begin slot_a <= 4'd9; fy_a <= vy - Y_HINT; end

    // menu highlight bar: 16 px tall around the selected row, x 40..279
    bar_a <= (ui_mode == UI_MENU) && (vx >= 10'd40) && (vx < 10'd280) &&
             (vy >= Y_R0 - 10'd4 + {menu_sel, 4'b0} + {menu_sel, 2'b0}) &&
             (vy <  Y_R0 + 10'd12 + {menu_sel, 4'b0} + {menu_sel, 2'b0});
    // progress bar while busy: x 64..255, 3 px
    pbar_a  <= (ui_mode == UI_BUSY) && (status != 5'd0) && (vx >= 10'd64) && (vx < 10'd256) &&
               (vy >= Y_PBAR) && (vy < Y_PBAR + 10'd3);
    pfill_a <= ({2'b00, vx - 10'd64} < ({2'b00, progress} * 10'd3 >> 2));
    // hairline under the cartridge info
    rule_a  <= (vy == Y_RULE) && (vx >= 10'd40) && (vx < 10'd280);
end

// ------------------------------------------------------------ stage B: character + colour
reg [7:0]  ch_b;
reg [23:0] col_b;
reg        inv_b;       // draw on the highlight bar
reg [2:0]  fy_b, fx_b;
reg        act_b, bar_b, pbar_b, pfill_b, rule_b;
reg [319:0] line;
reg [23:0]  lcol;
always @(*) begin
    item_idx = row_a;
    line = {40{8'h00}};
    lcol = C_FG;
    case (slot_a)
    4'd15: line = {"SaveSiphon", {30{8'h00}}};
    4'd1:  line = t_name;
    4'd2:  begin line = t_sub; lcol = C_DIM; end
    4'd3, 4'd4, 4'd5, 4'd6: begin
        case (ui_mode)
        UI_MENU: begin
            line = t_item;
            if (row_a != 2'd1 && row_a != 2'd3 && no_save && row_a != 2'd2) lcol = C_FAINT;
        end
        UI_BUSY: if (slot_a == 4'd4) line = (status == 5'd0 || status == 5'd21) ? t_head : t_head;
                 else if (slot_a == 4'd6 && status == 5'd7) begin line = t_file; lcol = C_DIM; end
        UI_RESULT: begin
            if (slot_a == 4'd3) begin
                line = (status == 5'd8) ? t_done : t_head;
                lcol = (status == 5'd8) ? C_OK : st_bad ? C_BAD : C_FG;
            end else if (slot_a == 4'd4) begin line = t_det1; lcol = C_DIM; end
            else if (slot_a == 4'd5) begin line = t_det2; lcol = C_DIM; end
            else if (slot_a == 4'd6 && (status == 5'd9 || status == 5'd12)) begin line = t_err; lcol = C_DIM; end
            else if (slot_a == 4'd6 && status == 5'd8) begin line = t_file; lcol = C_DIM; end
        end
        UI_CONFIRM: begin
            if (slot_a == 4'd3) line = t_head;
            else if (slot_a == 4'd4) begin line = t_det1; lcol = C_DIM; end
            else if (slot_a == 4'd5) begin line = t_det2; lcol = C_DIM; end
        end
        default: ;
        endcase
    end
    4'd7: if (ui_mode == UI_MENU) begin
              line = @SAVE_LBL@ | t_savev;
              lcol = C_DIM;
          end
    4'd8: if (ui_mode == UI_MENU) begin
              line = (is_gb ? @MAP_LBL@ | t_mapv : @ROM_LBL@ | t_romv);
              lcol = C_DIM;
          end
    4'd9: begin
        lcol = C_DIM;
        case (ui_mode)
        UI_MENU:    line = @H_MENU@;
        UI_CONFIRM: line = @H_CONFIRM@;
        UI_RESULT:  line = fatal ? @H_FATAL@ : (cart_kind == 2'd0 || status == 5'd20) ? @H_NOCART@ : @H_RESULT@;
        default:    line = (status >= 5'd5 && status != 5'd21) ? @H_BUSY@ : {40{8'h00}};
        endcase
    end
    default: ;
    endcase
end

// the info rows are two columns: label left in grey, value right in white
wire [5:0] info_split = 6'd20;

always @(posedge clk) begin
    ch_b    <= (col_a < 6'd40) ? line[8*(39-col_a) +: 8] : 8'h00;
    col_b   <= ((slot_a == 4'd7 || slot_a == 4'd8) && col_a >= info_split) ? C_FG : lcol;
    inv_b   <= bar_a;
    fy_b    <= fy_a;
    fx_b    <= fx_a;
    act_b   <= act_a;
    bar_b   <= bar_a;
    pbar_b  <= pbar_a;
    pfill_b <= pfill_a;
    rule_b  <= rule_a;
end

// ------------------------------------------------------------ stage C: font row
reg [7:0]  glyph_c;
reg [23:0] col_c;
reg [2:0]  fx_c;
reg        act_c, bar_c, pbar_c, pfill_c, rule_c;
always @(posedge clk) begin
    glyph_c <= font[{ch_b[6:0], fy_b}];
    col_c   <= col_b;
    fx_c    <= fx_b;
    act_c   <= act_b;
    bar_c   <= bar_b;
    pbar_c  <= pbar_b;
    pfill_c <= pfill_b;
    rule_c  <= rule_b;
end

// ------------------------------------------------------------ stage D: pixel
reg [3:0] de_d, hs_d, vs_d;
wire      ink = glyph_c[3'd7 - fx_c];
always @(posedge clk) begin
    if (!act_c)        rgb <= 24'h000000;
    else if (pbar_c)   rgb <= pfill_c ? C_FG : C_FAINT;
    else if (bar_c)    rgb <= ink ? C_BG : C_BAR;
    else if (rule_c)   rgb <= C_FAINT;
    else               rgb <= ink ? col_c : C_BG;

    de_d <= {de_d[2:0], active};
    hs_d <= {hs_d[2:0], (x == 10'd3)};
    vs_d <= {vs_d[2:0], (x == 10'd0 && y == 10'd0)};
    de   <= de_d[2];
    hs   <= hs_d[2];
    vs   <= vs_d[2];
end

endmodule

`default_nettype wire
'''

gba_sub = "Game Boy Advance  " + DOT + "  "
err_line_txt = "APF error code  "
grd_line_txt = "Guard code  "
reps = {
    "@HEAD@": head, "@DET1@": det1, "@DET2@": det2, "@DONE@": done,
    "@SAVEV@": savev, "@ROMV@": romv, "@MAPV@": mapv, "@MENU@": menu,
    "@GBA_SUB@": "{%d{8'h00}}, %s" % ((40 - len(gba_sub) - 4) // 2, lit(gba_sub)),
    "@GBA_SUB_PAD@": str(40 - (40 - len(gba_sub) - 4) // 2 - len(gba_sub) - 4),
    "@GB_SUB@": center("Game Boy"),
    "@GBC_SUB@": center("Game Boy Color"),
    "@ERR_LINE@": center(err_line_txt + " "),
    "@ERR_COL@": str((40 - len(err_line_txt) - 1) // 2 + len(err_line_txt)),
    "@GRD_LINE@": center(grd_line_txt + " "),
    "@GRD_COL@": str((40 - len(grd_line_txt) - 1) // 2 + len(grd_line_txt)),
    "@SAVE_LBL@": left("Save", 6),
    "@ROM_LBL@": left("ROM", 6),
    "@MAP_LBL@": left("Mapper", 6),
    "@H_MENU@": hints["menu"], "@H_CONFIRM@": hints["confirm"],
    "@H_RESULT@": hints["result"], "@H_NOCART@": hints["nocart"],
    "@H_FATAL@": hints["fatal"], "@H_BUSY@": hints["busy"],
}
for k, v in reps.items():
    V = V.replace(k, v)
assert "@" not in V.replace("@(", "").replace("@*", ""), [l for l in V.splitlines() if "@" in l and "@(" not in l]
open(sys.argv[1], "w").write(V)
